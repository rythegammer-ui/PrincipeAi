"use server";

import { eq } from "drizzle-orm";
import { revalidatePath } from "next/cache";
import { z } from "zod";
import { extractEmailBody } from "@/components/funnels/automation-utils";
import { getDb, schema } from "@/db";
import type { EmailStatus } from "@/db/schema";
import { assertAdmin } from "@/lib/auth";
import { hasRedactedSignInLink, sendEmail } from "@/lib/email";
import { rateLimit } from "@/lib/rate-limit";

export type ResendResult = { ok: true; status: EmailStatus } | { ok: false; error: string };

/** Re-sends a failed email with its original content (a new Email Log entry records the attempt). */
export async function resendEmailAction(emailId: string): Promise<ResendResult> {
  const session = await assertAdmin();
  const id = z.uuid().safeParse(emailId);
  if (!id.success) return { ok: false, error: "Invalid email." };
  const limit = await rateLimit(`admin-resend:${session.email}`, 20, 600);
  if (!limit.ok) return { ok: false, error: "Too many resends in a short time. Please wait a few minutes." };

  const db = await getDb();
  const [log] = await db.select().from(schema.emailLog).where(eq(schema.emailLog.id, id.data)).limit(1);
  if (!log) return { ok: false, error: "This email no longer exists." };
  if (log.status !== "failed") return { ok: false, error: "Only failed emails can be resent." };
  // The log keeps sign-in links redacted, so re-sending would deliver a broken link.
  if (hasRedactedSignInLink(log.html)) {
    return {
      ok: false,
      error: "Emails with a one-time sign-in link can't be resent (the log keeps the link redacted). Ask the student to request a fresh link on the student login page (/login).",
    };
  }
  const inner = extractEmailBody(log.html);
  if (!inner) return { ok: false, error: "This email's content can't be resent. Send a new one from the contact's page instead." };

  const [contact] = log.contactId
    ? await db
        .select({ unsubscribeToken: schema.contacts.unsubscribeToken, unsubscribed: schema.contacts.unsubscribed })
        .from(schema.contacts)
        .where(eq(schema.contacts.id, log.contactId))
        .limit(1)
    : [];

  // Stored HTML was generated by sendEmail (Markdown rendered with raw HTML escaped), so it is system-authored.
  const result = await sendEmail({
    to: log.to,
    subject: log.subject,
    html: inner,
    kind: log.kind,
    contactId: log.contactId,
    unsubscribeToken: contact?.unsubscribeToken ?? null,
    unsubscribed: contact?.unsubscribed ?? false,
  });
  revalidatePath("/admin/emails");
  revalidatePath(`/admin/emails/${log.id}`);
  if (log.contactId) revalidatePath(`/admin/contacts/${log.contactId}`);
  return { ok: true, status: result.status };
}
